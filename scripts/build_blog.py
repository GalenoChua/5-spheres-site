WORDS = {
    "en": {"more_label": "More from the field", "more_heading": "Keep going",
           "cta": "Read it &#8594;",
           "months": ["January", "February", "March", "April", "May", "June",
                      "July", "August", "September", "October", "November",
                      "December"]},
    "pl": {"more_label": "Wiecej z terenu", "more_heading": "Czytaj dalej",
           "cta": "Czytaj &#8594;",
           "months": ["stycznia", "lutego", "marca", "kwietnia", "maja",
                      "czerwca", "lipca", "sierpnia", "wrzesnia",
                      "pazdziernika", "listopada", "grudnia"]},
}


def human_date(iso, lang):
    d = datetime.date.fromisoformat(iso)
    month = WORDS[lang]["months"][d.month - 1]
    return "%d %s %d" % (d.day, month, d.year)


def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


# ------------------------------------------------------------- the source ---
def load_sources():
    """Every markdown file under content/, with its front matter."""
    posts = []
    if not os.path.isdir(CONTENT):
        return posts
    for base, _dirs, files in os.walk(CONTENT):
        for f in sorted(files):
            if not f.endswith(".md"):
                continue
            # content/README.md documents the layout for whoever opens the folder;
            # it is not a post and has no front matter. Walking it exited the build
            # before a single post was rendered, so the first markdown post could
            # never be published. A leading underscore is the same case: a note to
            # the next person, kept beside the posts rather than away from them.
            if f == "README.md" or f.startswith("_"):
                continue
            path = os.path.join(base, f)
            raw = io.open(path, encoding="utf-8").read()
            m = re.match(r"^---\n(.*?)\n---\n(.*)$", raw, re.S)
            if not m:
                sys.exit("%s has no front matter block" % path)
            meta = yaml.safe_load(m.group(1)) or {}
            meta["_body_md"] = m.group(2)
            meta["_path"] = path
            for required in ("title", "description", "date", "lang"):
                if not meta.get(required):
                    sys.exit("%s is missing `%s` in its front matter"
                             % (path, required))
            if meta["lang"] not in SECTIONS:
                sys.exit("%s has lang %r, expected one of %s"
                         % (path, meta["lang"], sorted(SECTIONS)))
            meta.setdefault("slug", os.path.splitext(f)[0])
            meta.setdefault("kicker", SECTIONS[meta["lang"]]["label"])
            meta.setdefault("updated", meta["date"])
            meta.setdefault("image", "/og.png")
            meta.setdefault("heading", meta["title"])
            posts.append(meta)
    return posts


def url_for(meta):
    return "/%s/%s/" % (SECTIONS[meta["lang"]]["dir"].replace(os.sep, "/"),
                        meta["slug"])


# ------------------------------------------------------------- rendering ---
def render(meta, siblings, parts):
    nav, footer, beacon = parts
    lang = meta["lang"]
    url = url_for(meta)
    body = md_lib.markdown(meta["_body_md"],
                           extensions=["extra", "sane_lists"])
    body = "\n".join("      " + line if line.strip() else line
                     for line in body.split("\n"))

    # hreflang, only when a counterpart genuinely exists. Pointing at a page
    # that is not there is worse than saying nothing.
    alternates = ""
    twin = meta.get("_twin")
    if twin:
        pairs = [(lang, url), (twin["lang"], url_for(twin))]
        for code, href in pairs:
            alternates += ('  <link rel="alternate" hreflang="%s" href="%s%s">\n'
                           % (code, SITE, href))
        alternates += ('  <link rel="alternate" hreflang="x-default" href="%s%s">\n'
                       % (SITE, url_for(meta if lang == "en" else twin)))

    schema = """  {
    "@context": "https://schema.org",
    "@type": "Article",
    "headline": "%s",
    "description": "%s",
    "inLanguage": "%s",
    "author": { "@type": "Person", "name": "Galeno Chua" },
    "publisher": { "@type": "Organization", "name": "The 5 Spheres of Empathy" },
    "datePublished": "%s",
    "dateModified": "%s",
    "url": "%s%s"
  }""" % (esc(meta["title"]), esc(meta["description"]), lang,
          meta["date"], meta["updated"], SITE, url)

    # The three most recent OTHER posts in the same language, rather than
    # whatever was recent on the day this post was written.
    others = [p for p in siblings
              if p["lang"] == lang and p["slug"] != meta["slug"]]
    others.sort(key=lambda p: p["date"], reverse=True)
    cards = "".join(
        CARD.format(title=esc(p["title"]), description=esc(p["description"]),
                    url=p["url"], cta=WORDS[lang]["cta"])
        for p in others[:3])
    more = MORE.format(cards=cards, **{k: WORDS[lang][k]
                                       for k in ("more_label", "more_heading")}) if cards else ""

    return PAGE.format(
        lang=lang, title=esc(meta["title"]), description=esc(meta["description"]),
        site=SITE, url=url, image=meta["image"],
        published=meta["date"], modified=meta["updated"],
        alternates=alternates, schema=schema, nav=nav, footer=footer,
        beacon=beacon, kicker=esc(meta["kicker"]), heading=esc(meta["heading"]),
        datetext=human_date(str(meta["date"]), lang), body=body, more=more)


# ------------------------------------------------- scanning rendered pages ---
SKIP_DIRS = {".git", "node_modules", ".netlify", "ops-log", "scripts",
             "content", "5 Spheres Admin", "5 Spheres of Empathy",
             "5 Spheres of Empathy Books", "Global Sustainability Tours",
             "course-export", "renders"}


def all_pages():
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS
                   and not d.startswith(".") and not d.startswith("_")]
        for f in files:
            if f.startswith("PREVIEW-") or f.startswith("_"):
                continue
            if f.endswith(".html"):
                yield os.path.join(base, f)


def page_url(path):
    rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
    if rel.endswith("/index.html"):
        return "/" + rel[: -len("index.html")]
    if rel == "index.html":
        return "/"
    return "/" + rel


def scan_posts():
    """Read title, date and description back off every rendered post.

    Deliberately reads the RENDERED page rather than the markdown, so the six
    hand-written posts appear in the index and the sitemap on exactly the same
    footing as generated ones.
    """
    found = []
    for lang, sec in SECTIONS.items():
        d = os.path.join(ROOT, sec["dir"])
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            path = os.path.join(d, name, "index.html")
            if not os.path.isfile(path):
                continue
            html = io.open(path, encoding="utf-8").read()
            def grab(pattern, default=""):
                m = re.search(pattern, html, re.S)
                return m.group(1).strip() if m else default
            title = grab(r"<title>(.*?)\s*\|")
            date = grab(r'"datePublished":\s*"(\d{4}-\d{2}-\d{2})"')
            if not title or not date:
                print("  skipped %s (no title or datePublished)"
                      % page_url(path))
                continue
            found.append({
                "lang": lang, "slug": name, "title": title, "date": date,
                "updated": grab(r'"dateModified":\s*"(\d{4}-\d{2}-\d{2})"', date),
                "description": grab(r'<meta name="description" content="(.*?)">'),
                "kicker": grab(r'<div class="kicker">(.*?)</div>',
                               SECTIONS[lang]["label"]),
                "url": page_url(path),
            })
    return found


# ----------------------------------------------------------------- index ---
ENTRY = """      <div class="feed-entry">
        <div class="feed-date">{datetext}</div>
        <div class="kicker">{kicker}</div>
        <h3><a href="{url}">{title}</a></h3>
        <p>{description}</p>
      </div>
"""


def build_index(posts, lang="en"):
    """Rewrite the listing between the two markers, newest first."""
    index_path = os.path.join(ROOT, SECTIONS[lang]["dir"], "index.html")
    if not os.path.isfile(index_path):
        return None, None
    html = io.open(index_path, encoding="utf-8").read()
    mine = sorted([p for p in posts if p["lang"] == lang],
                  key=lambda p: p["date"], reverse=True)
    feed = "".join(ENTRY.format(datetext=human_date(p["date"], lang),
                                kicker=p["kicker"], url=p["url"],
                                title=p["title"], description=p["description"])
                   for p in mine)
    block = FEED_START + "\n" + feed + "    " + FEED_END

    if FEED_START in html:
        new = re.sub(re.escape(FEED_START) + r".*?" + re.escape(FEED_END),
                     block, html, flags=re.S)
    else:
        # First run: wrap whatever feed-entries are already there.
        m = re.search(r'(\s*<div class="feed-entry">.*</div>\s*)(?=\s*</div>\s*</section>)',
                      html, re.S)
        if not m:
            print("  could not find the feed block in %s; index left alone"
                  % page_url(index_path))
            return html, html
        new = html[:m.start(1)] + "\n      " + block + "\n" + html[m.end(1):]
    return html, new


# --------------------------------------------------------------- sitemap ---
# Pages that exist and are not FOR the public. A sitemap is a request to index,
# so sweeping the directory and submitting everything is worse than a stale
# file: it hands Google a facilitator console and a per-person results page.
#
# Each line says what it is, because the only way this list stays correct is if
# the next person can tell a deliberate exclusion from a forgotten one.
NOINDEX = [
    ("/skilldrills/public-speaking/facilitator/", "the room console, for G"),
    ("/skilldrills/public-speaking/new/", "creates a session"),
    ("/skilldrills/public-speaking/results/", "one participant's scores"),
    ("/skilldrills/public-speaking/room/", "live session view"),
    ("/skilldrills/thanks/", "post-submit confirmation"),
    ("/skilldrills/decks/", "slide decks, including _superseded"),
    ("/quad/results/", "one participant's scores"),
    ("/pah-pitch/", "a pitch, not a public page"),
    ("/video/", "working footage"),
    ("/Course Core Competencies/", "internal planning, and the URL has spaces"),
    ("/pt2/", "ASC Credibility Programme session tool, and it declares no robots tag"),
]


def last_changed(path):
    """When this file last actually changed, asked of git first.

    Not mtime alone. A fresh `git clone` stamps every file with the clone time,
    so an mtime-only sitemap would claim the entire site changed on whatever day
    someone happened to check it out, and the committed file would be rewritten
    wholesale on the next build. git knows the real answer and it survives a
    clone; mtime is the fallback for a file not yet committed.
    """
    try:
        import subprocess
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", path],
            cwd=ROOT, capture_output=True, text=True, timeout=15)
        stamp = out.stdout.strip()
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", stamp):
            return stamp
    except Exception:
        pass                      # no git, or not a repo: fall through
    return datetime.date.fromtimestamp(os.path.getmtime(path)).isoformat()


def public(url, html=""):
    """False when a page should not be offered to a search engine.

    The page's OWN robots meta wins, because that is the authoritative signal
    and it is already right on several pages: /quad/, /watch/sensing-drill/ and
    the public speaking scoring card all say noindex. Listing a noindexed page
    in a sitemap is a straight contradiction, asking Google to index something
    the page then refuses.

    The list below is only for pages that declare nothing.
    """
    if re.search(r'<meta[^>]+name="robots"[^>]+content="[^"]*noindex', html, re.I):
        return False
    if url.endswith("worksheet-print.html") or url.endswith("/print.html"):
        return False
    return not any(url.startswith(prefix) for prefix, _why in NOINDEX)


def build_sitemap(posts):
    """Every PUBLIC page, with a lastmod that is actually true.

    The hand-written version carried 31 August on 21 of its 48 entries while
    the pages had moved on, and it listed nothing nobody remembered to add.
    """
    dates = {p["url"]: p["updated"] for p in posts}
    rows = []
    for path in sorted(all_pages(), key=page_url):
        url = page_url(path)
        # Print-only and machine pages do not belong in a sitemap.
        if url.endswith("worksheet-print.html") or "/room/" in url:
            continue
        html = io.open(path, encoding="utf-8").read()
        if not public(url, html):
            continue
        last = dates.get(url) or last_changed(path)
        rows.append("  <url>\n    <loc>%s%s</loc>\n    <lastmod>%s</lastmod>\n  </url>"
                    % (SITE, url, last))
    header = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Generated by scripts/build_blog.py. Do not hand edit: a post added\n"
        "     by hand to the old one is how pages went missing. -->\n"
        '<urlset xmlns="%s">\n' % SITEMAP_NS)
    return header + "\n".join(rows) + "\n</urlset>\n"


# ------------------------------------------------------------------ main ---
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if anything on disk is out of date")
    args = ap.parse_args()

    parts = chrome()
    sources = load_sources()

    # pair translations both ways before rendering
    by_key = {}
    for s in sources:
        by_key[(s["lang"], s["slug"])] = s
    for s in sources:
        twin_slug = s.get("translation")
        if twin_slug:
            other = "pl" if s["lang"] == "en" else "en"
            twin = by_key.get((other, twin_slug))
            if not twin:
                sys.exit("%s names translation %r, which does not exist in %s"
                         % (s["_path"], twin_slug, other))
            s["_twin"] = twin

    changed = []

    # 1. render markdown posts
    if sources:
        # THE "KEEP GOING" CARDS READ EVERY POST ON DISK, NOT ONLY THE MARKDOWN ONES.
        # This used to be `[dict(s, url=url_for(s)) for s in sources]`, which meant a
        # post's siblings were the other MARKDOWN posts. With one markdown post and six
        # hand-written ones, `others` was empty and the first post rendered with no cards
        # at all, which is how it shipped on 28 October 2026 before anyone looked at the
        # foot of the page. The index and the sitemap already scan rendered HTML for
        # exactly this reason, stated twelve lines into this file: old and new posts on
        # the same footing, one code path rather than two. The cards were the one place
        # that still had two. A markdown source wins over its own rendered page, because
        # it is the newer of the two and may not be rendered yet on a first build.
        by_slug = {(p["lang"], p["slug"]): p for p in scan_posts()}
        by_slug.update({(s["lang"], s["slug"]): dict(s, url=url_for(s))
                        for s in sources})
        siblings = list(by_slug.values())
        for s in sources:
            out_dir = os.path.join(ROOT, SECTIONS[s["lang"]]["dir"], s["slug"])
            out = os.path.join(out_dir, "index.html")
            html = render(s, siblings, parts)
            old = io.open(out, encoding="utf-8").read() if os.path.isfile(out) else None
            if old != html:
                changed.append(page_url(out))
                if not args.check:
                    os.makedirs(out_dir, exist_ok=True)
                    io.open(out, "w", encoding="utf-8", newline="").write(html)

    # 2. index and sitemap from what is actually on disk
    posts = scan_posts()
    for lang in SECTIONS:
        old, new = build_index(posts, lang)
        if old is None or old == new:
            continue
        changed.append("/%s/ (index)" % SECTIONS[lang]["dir"].replace(os.sep, "/"))
        if not args.check:
            io.open(os.path.join(ROOT, SECTIONS[lang]["dir"], "index.html"),
                    "w", encoding="utf-8", newline="").write(new)

    sm_path = os.path.join(ROOT, "sitemap.xml")
    sm = build_sitemap(posts)
    old_sm = io.open(sm_path, encoding="utf-8").read() if os.path.isfile(sm_path) else None
    if old_sm != sm:
        changed.append("/sitemap.xml")
        if not args.check:
            io.open(sm_path, "w", encoding="utf-8", newline="").write(sm)

    print("%d markdown source(s), %d rendered post(s), %d url(s) in the sitemap"
          % (len(sources), len(posts), sm.count("<loc>")))
    if args.check:
        if changed:
            print("\nout of date:")
            for c in changed:
                print("  " + c)
            print("\nrun: python scripts/build_blog.py")
            return 1
        print("blog, index and sitemap are up to date")
        return 0
    for c in changed:
        print("  wrote " + c)
    if not changed:
        print("nothing to do")
    return 0


if __name__ == "__main__":
    sys.exit(main())
