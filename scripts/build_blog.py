# -*- coding: utf-8 -*-
"""Write a post in markdown; this renders the page, the index and the sitemap.

    python scripts/new_post.py "A title"      scaffold a markdown file
    python scripts/build_blog.py              render everything
    python scripts/build_blog.py --check      fail if anything is out of date

WHY THIS EXISTS. Publishing a field note meant hand-writing about 180 lines of
HTML, of which roughly 115 were chrome repeated identically in every post, then
remembering to add an entry to field-notes/index.html and another to
sitemap.xml. There are six posts. Content is G's strength, so the thing stopping
him was never the writing.

It also fixes two silent defects found on 26 October 2026:

  * sitemap.xml was maintained BY HAND. Most entries carried a lastmod of
    31 August while the pages had changed since, and a new post that nobody
    remembered to add is simply invisible to Google.
  * the "Keep going" cards at the foot of each post were hand-picked, so they
    pointed at whatever was recent when that post was written and never moved.

WHAT IT DELIBERATELY DOES NOT DO. It does not rewrite the six existing posts.
Their bodies carry hand-made markup and re-rendering them risks changing pages
that work. Instead the index and the sitemap are built by SCANNING the rendered
HTML on disk, whatever produced it, so old and new posts are treated alike and
there is one code path rather than two.

THE CHROME IS NOT COPIED INTO THIS FILE. The nav and footer are read from a
donor page at build time, so when the navigation changes on the site, every post
picks it up on the next build. A copy in here would drift, quietly, and the
first anyone would know is a post with a menu missing a section.
"""
import argparse
import datetime
import io
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

try:
    import markdown as md_lib
    import yaml
except ImportError as err:                                  # pragma: no cover
    sys.exit("needs `pip install markdown pyyaml` (%s)" % err)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://5spheresofempathy.com"
CONTENT = os.path.join(ROOT, "content")
DONOR = os.path.join(ROOT, "field-notes", "index.html")

# Where a post lands, per language. Polish gets Polish words in the path,
# because the slug is part of what a Polish search is matched against.
SECTIONS = {
    "en": {"dir": "field-notes", "label": "Field Notes"},
    "pl": {"dir": os.path.join("pl", "notatki"), "label": "Notatki"},
}

FEED_START = "<!-- FEED:START generated by scripts/build_blog.py -->"
FEED_END = "<!-- FEED:END -->"

SITEMAP_NS = "http://www.sitemaps.org/schemas/sitemap/0.9"


# ----------------------------------------------------------------- chrome ---
def chrome():
    """Read <nav> and <footer> off a real page rather than keeping a copy."""
    html = io.open(DONOR, encoding="utf-8").read()
    nav = re.search(r"<nav>.*?</nav>", html, re.S)
    foot = re.search(r"<footer>.*?</footer>", html, re.S)
    beacon = re.search(r'<script[^>]*data-cf-beacon[^>]*></script>', html)
    if not nav or not foot:
        sys.exit("could not read the nav/footer from %s" % DONOR)
    if not beacon:
        sys.exit("no analytics beacon on %s; build_blog would strip it from "
                 "every post it renders" % DONOR)
    return nav.group(0), foot.group(0), beacon.group(0)


